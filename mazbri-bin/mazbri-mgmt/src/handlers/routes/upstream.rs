use super::super::state::AppState;
use super::super::upstream_connector_handlers;
use axum::{
    Router,
    routing::{get, post},
};

pub fn routes() -> Router<AppState> {
    Router::new()
        .route(
            "/upstream-connectors/drafts",
            get(upstream_connector_handlers::list_drafts)
                .post(upstream_connector_handlers::create_draft),
        )
        .route(
            "/upstream-connectors/drafts/{id}",
            get(upstream_connector_handlers::get_draft)
                .patch(upstream_connector_handlers::update_draft)
                .delete(upstream_connector_handlers::delete_draft),
        )
        .route(
            "/upstream-connectors/drafts/{id}/validate",
            post(upstream_connector_handlers::validate_draft),
        )
        .route(
            "/upstream-connectors/drafts/{id}/transform-preview",
            post(upstream_connector_handlers::transform_preview),
        )
        .route(
            "/upstream-connectors/drafts/{id}/runs",
            get(upstream_connector_handlers::list_runs)
                .post(upstream_connector_handlers::create_run),
        )
        .route(
            "/upstream-connectors/runs/{run_id}",
            get(upstream_connector_handlers::get_run),
        )
        .route(
            "/upstream-connectors/drafts/{id}/publish",
            post(upstream_connector_handlers::publish_draft),
        )
        .route(
            "/upstream-connectors/import/curl",
            post(upstream_connector_handlers::import_curl),
        )
        .route(
            "/upstream-connectors/import/postman",
            post(upstream_connector_handlers::import_postman),
        )
        .route(
            "/upstream-connectors/import/openapi",
            post(upstream_connector_handlers::import_openapi),
        )
        .route(
            "/upstream-connectors/drafts/from-supplier/{supplier_id}",
            post(upstream_connector_handlers::draft_from_supplier),
        )
        .route(
            "/upstream-connectors/drafts/{id}/export/postman",
            get(upstream_connector_handlers::export_postman),
        )
        .route(
            "/upstream-connectors/suppliers/{supplier_id}/versions",
            get(upstream_connector_handlers::list_versions),
        )
        .route(
            "/upstream-connectors/suppliers/{supplier_id}/versions/{vid}/diff",
            get(upstream_connector_handlers::version_diff),
        )
        .route(
            "/upstream-connectors/suppliers/{supplier_id}/rollback",
            post(upstream_connector_handlers::rollback),
        )
        .route(
            "/upstream-connectors/suppliers/{supplier_id}/runs",
            post(upstream_connector_handlers::live_run),
        )
        .route(
            "/upstream-connectors/artifacts",
            post(upstream_connector_handlers::create_artifact),
        )
        .route(
            "/upstream-connectors/artifacts/{id}",
            get(upstream_connector_handlers::get_artifact),
        )
}
